/**
 * Explicit allow-list for the Super-Admin data manager.
 *
 * Nothing outside this registry is reachable through /admin/data. Columns are
 * declared by hand so a future migration cannot silently expose a new column;
 * sensitive values are omitted from every response and export.
 */

export type ColumnType = "text" | "longtext" | "integer" | "real" | "boolean" | "json" | "datetime" | "enum";

export type ForeignKey = {
  table: string;
  value: string;
  label: string;
};

export type ColumnDef = {
  name: string;
  label: string;
  type: ColumnType;
  readonly?: boolean;
  hidden?: boolean;
  sensitive?: boolean;
  nullable?: boolean;
  enumValues?: string[];
  fk?: ForeignKey;
  maxLength?: number;
};

export type TableDef = {
  name: string;
  label: string;
  section: "Content" | "People" | "Attempts" | "Community" | "Site" | "Operations";
  pk: string;
  columns: ColumnDef[];
  softDelete?: boolean;
  editable?: boolean;
  deletable?: boolean;
  note?: string;
};

function titleize(value: string): string {
  return value
    .replace(/_/g, " ")
    .replace(/\b\w/g, (character) => character.toUpperCase());
}

function col(
  name: string,
  type: ColumnType,
  options: Partial<Omit<ColumnDef, "name" | "type" | "label">> = {},
): ColumnDef {
  return {
    name,
    type,
    label: titleize(name),
    nullable: true,
    ...options,
  };
}

