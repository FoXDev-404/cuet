export const TABLES_BY_NAME = new Map(TABLES.map((table) => [table.name, table]));

export function getTable(name: string): TableDef | null {
  return TABLES_BY_NAME.get(name) ?? null;
}

export function visibleColumns(table: TableDef): ColumnDef[] {
  return table.columns.filter((column) => !column.hidden && !column.sensitive);
}

export function editableColumns(table: TableDef): ColumnDef[] {
  return table.columns.filter((column) => !column.hidden && !column.sensitive && !column.readonly);
}

export function labelForColumn(table: TableDef, name: string): string {
  return table.columns.find((column) => column.name === name)?.label ?? titleize(name);
}
